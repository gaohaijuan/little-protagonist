function validateNickname(value) {
  if (typeof value !== 'string' || /[\u0000-\u001f\u007f-\u009f\u2028-\u202e\u2066-\u2069]/.test(value) || Array.from(value.trim()).length < 1 || Array.from(value.trim()).length > 16) {
    throw Object.assign(new Error('家长称呼请填写1至16个字，不含换行或控制字符。'), { code: 'AUTH_INVALID_NICKNAME' });
  }
  return value.trim();
}
